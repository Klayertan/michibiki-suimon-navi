#!/usr/bin/env node
// Generates a SYNTHETIC NMEA log plus its marks file, for exercising the
// analysis pipeline without a receiver.
//
//   ⚠ NOTHING THIS SCRIPT PRODUCES IS A MEASUREMENT.
//
// Every file it writes is stamped SYNTHETIC in its own first line and its
// filename, and the marks file carries `"synthetic": true`. This exists so
// the software can be tested — that the segment assignment lines up, that a
// filter chain does what it claims, that a verdict flips when the noise level
// changes — NOT so the experiment can be "run" at a desk.
//
// The noise model here is a convenient fiction: AR(1) noise plus optional
// linear drift. Real GNSS vertical error is worse than AR(1), is not
// stationary, and depends on sky view, multipath and the ionosphere. A PASS
// obtained from this generator says the analysis code works. It says nothing
// whatsoever about whether QZ1 can measure a 10 mm step, and no output of
// this script may be presented as evidence that it can.
//
// Usage:
//   node experiments/qz1-water-level/scripts/make-synthetic-log.mjs \
//     --out tests/fixtures/qz1-water-level \
//     --noise-sd-mm 40 --drift-mm-per-hour 0 --seed 7
//
// Options:
//   --heights 0,10,20,30,50,100   reference heights in mm
//   --dwell 120                   seconds per level
//   --settle 15                   seconds discarded at the start of each level
//   --rate 1                      fixes per second
//   --noise-sd-mm 40              sd of the AR(1) altitude noise
//   --phi 0.9                     AR(1) coefficient (sample-to-sample memory)
//   --drift-mm-per-hour 0         linear drift added over the whole run
//   --gap-seconds 30              repositioning time between levels
//   --no-descending               ascend only
//   --seed 1                      PRNG seed (deterministic output)
//   --name synthetic-baseline     output filename stem

import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const args = parseArgs(process.argv.slice(2));

const heights = (args.heights ?? "0,10,20,30,50,100").split(",").map(Number);
const dwellSeconds = Number(args.dwell ?? 120);
const settleSeconds = Number(args.settle ?? 15);
const rateHz = Number(args.rate ?? 1);
const noiseSdMm = Number(args["noise-sd-mm"] ?? 40);
const phi = Number(args.phi ?? 0.9);
const driftMmPerHour = Number(args["drift-mm-per-hour"] ?? 0);
const gapSeconds = Number(args["gap-seconds"] ?? 30);
const includeDescending = args["no-descending"] === undefined;
const seed = Number(args.seed ?? 1);
const name = args.name ?? "synthetic-baseline";
const outDir = resolve(args.out ?? "tests/fixtures/qz1-water-level");

// A fixed, obviously-fake position: a round number in the middle of nowhere,
// so a synthetic file can never be mistaken for a real field recording and
// never leaks a real location into the repository.
const BASE_LAT = 35.0;
const BASE_LON = 135.0;
const BASE_ALTITUDE_M = 50.0;
const GEOID_SEPARATION_M = 36.0;
const START_UTC = Date.UTC(2026, 0, 15, 2, 0, 0);

const random = mulberry32(seed);
const plan = buildPlan(heights, includeDescending);

const lines = [
  "# SYNTHETIC DATA — generated by experiments/qz1-water-level/scripts/make-synthetic-log.mjs",
  "# NOT A MEASUREMENT. Produced by a noise model, not by a receiver.",
  `# seed=${seed} noise_sd_mm=${noiseSdMm} phi=${phi} drift_mm_per_hour=${driftMmPerHour}`
];
const marks = [];

let clockMs = START_UTC;
let noiseMm = 0;
let sampleCount = 0;
// Declared before the emit loop: emitSeconds() reads it on its first call.
let lastHeightMm = 0;
const noiseInnovationSd = noiseSdMm * Math.sqrt(1 - phi * phi);

for (const step of plan) {
  // Repositioning gap: samples still stream, and they belong to no level.
  emitSeconds(gapSeconds, null);

  const startMs = clockMs;
  emitSeconds(dwellSeconds, step.referenceHeightMm);
  marks.push({
    stepIndex: step.stepIndex,
    referenceHeightMm: step.referenceHeightMm,
    visitIndex: step.visitIndex,
    direction: step.direction,
    startMs,
    endMs: clockMs,
    settleSeconds
  });
}

function emitSeconds(seconds, referenceHeightMm) {
  const samples = Math.round(seconds * rateHz);
  for (let index = 0; index < samples; index += 1) {
    noiseMm = phi * noiseMm + gaussian(random) * noiseInnovationSd;
    const driftMm = driftMmPerHour * ((clockMs - START_UTC) / 3600000);
    // During a repositioning gap the receiver is somewhere between two
    // heights; modelling it as the midpoint would be a guess, so it simply
    // stays at the previous height until the new dwell begins. Those samples
    // are unlabelled either way, and the analysis excludes them.
    const trueHeightMm = referenceHeightMm ?? lastHeightMm;
    if (referenceHeightMm !== null) {
      lastHeightMm = referenceHeightMm;
    }
    const altitudeM = BASE_ALTITUDE_M + (trueHeightMm + noiseMm + driftMm) / 1000;
    lines.push(...sentencesFor(clockMs, altitudeM));
    clockMs += 1000 / rateHz;
    sampleCount += 1;
  }
}

function sentencesFor(epochMs, altitudeM) {
  const date = new Date(epochMs);
  const hhmmss = `${pad(date.getUTCHours())}${pad(date.getUTCMinutes())}${pad(date.getUTCSeconds())}.00`;
  const ddmmyy = `${pad(date.getUTCDate())}${pad(date.getUTCMonth() + 1)}${String(date.getUTCFullYear()).slice(2)}`;
  const satellites = 8 + Math.floor(random() * 4);
  const hdop = (0.7 + random() * 0.6).toFixed(1);
  const vdop = (1.1 + random() * 0.8).toFixed(1);
  const pdop = (Math.sqrt(Number(hdop) ** 2 + Number(vdop) ** 2)).toFixed(1);

  return [
    withChecksum(`GPGGA,${hhmmss},${toNmeaLat(BASE_LAT)},N,${toNmeaLon(BASE_LON)},E,1,${pad(satellites)},${hdop},${altitudeM.toFixed(3)},M,${GEOID_SEPARATION_M.toFixed(1)},M,,`),
    withChecksum(`GNGSA,A,3,01,02,03,04,05,06,07,08,,,,,${pdop},${hdop},${vdop}`),
    withChecksum(`GNRMC,${hhmmss},A,${toNmeaLat(BASE_LAT)},N,${toNmeaLon(BASE_LON)},E,0.0,0.0,${ddmmyy},,,A`),
    withChecksum(`GNZDA,${hhmmss},${pad(date.getUTCDate())},${pad(date.getUTCMonth() + 1)},${date.getUTCFullYear()},,`)
  ];
}

mkdirSync(outDir, { recursive: true });
const nmeaPath = join(outDir, `${name}.SYNTHETIC.nmea`);
const marksPath = join(outDir, `${name}.SYNTHETIC.marks.json`);
const configPath = join(outDir, `${name}.SYNTHETIC.config.json`);

writeFileSync(nmeaPath, `${lines.join("\r\n")}\r\n`, "utf8");
writeFileSync(marksPath, `${JSON.stringify({
  synthetic: true,
  warning: "SYNTHETIC — generated by a noise model. Not a measurement. Never cite as evidence about QZ1 hardware.",
  generator: {
    seed, noiseSdMm, phi, driftMmPerHour, dwellSeconds, settleSeconds, rateHz, gapSeconds, heights, includeDescending
  },
  marks
}, null, 2)}\n`, "utf8");
writeFileSync(configPath, `${JSON.stringify({
  experiment: `${name}-SYNTHETIC`,
  stage: "controlled-rig",
  sensor: "SYNTHETIC (not a real receiver)",
  reference_heights_mm: heights,
  include_descending: includeDescending,
  location: "",
  operator: "",
  notes: "SYNTHETIC fixture. Generated by make-synthetic-log.mjs — contains no measured data.",
  sampling_configuration: { dwell_seconds: dwellSeconds, settle_seconds: settleSeconds },
  tolerance_mm: 10
}, null, 2)}\n`, "utf8");

process.stdout.write(
  `SYNTHETIC fixture written (not a measurement):\n`
  + `  ${nmeaPath}\n  ${marksPath}\n  ${configPath}\n`
  + `  ${sampleCount} fixes, ${plan.length} levels, noise sd ${noiseSdMm} mm (phi ${phi}), drift ${driftMmPerHour} mm/h\n`
);

// ---------------------------------------------------------------------------

function buildPlan(values, descending) {
  const unique = [...new Set(values)].sort((a, b) => a - b);
  const ordered = descending ? [...unique, ...[...unique].reverse().slice(1)] : unique;
  return ordered.map((referenceHeightMm, index) => ({
    stepIndex: index,
    referenceHeightMm,
    direction: index < unique.length ? "ascending" : "descending",
    visitIndex: ordered.slice(0, index).filter((value) => value === referenceHeightMm).length
  }));
}

function withChecksum(body) {
  let checksum = 0;
  for (const character of body) {
    checksum ^= character.charCodeAt(0);
  }
  return `$${body}*${checksum.toString(16).toUpperCase().padStart(2, "0")}`;
}

function toNmeaLat(degrees) {
  const whole = Math.floor(Math.abs(degrees));
  const minutes = (Math.abs(degrees) - whole) * 60;
  return `${pad(whole)}${minutes.toFixed(4).padStart(7, "0")}`;
}

function toNmeaLon(degrees) {
  const whole = Math.floor(Math.abs(degrees));
  const minutes = (Math.abs(degrees) - whole) * 60;
  return `${String(whole).padStart(3, "0")}${minutes.toFixed(4).padStart(7, "0")}`;
}

function pad(value) {
  return String(value).padStart(2, "0");
}

function mulberry32(a) {
  return function next() {
    a |= 0;
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Box–Muller. */
function gaussian(rng) {
  let u = 0;
  let v = 0;
  while (u === 0) u = rng();
  while (v === 0) v = rng();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (!token.startsWith("--")) continue;
    const key = token.slice(2);
    const next = argv[index + 1];
    if (next === undefined || next.startsWith("--")) {
      parsed[key] = true;
    } else {
      parsed[key] = next;
      index += 1;
    }
  }
  return parsed;
}
